import { execFileSync } from "node:child_process";
import { copyFile, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const wasmRoot = fileURLToPath(new URL("../", import.meta.url));
const repositoryRoot = resolve(wasmRoot, "..");
const require = createRequire(import.meta.url);
const args = process.argv.slice(2);
if (args.some((argument) => argument !== "--skip-cargo") || args.length > 1) {
    throw new Error("Usage: npm run build [-- --skip-cargo]");
}

const lock = await readFile(join(repositoryRoot, "Cargo.lock"), "utf8");
const packages = lock.split("[[package]]");
const versions = packages.filter((entry) => /^name = "wasm-bindgen"$/m.test(entry))
    .map((entry) => entry.match(/^version = "([^"]+)"$/m)?.[1]);
if (versions.length !== 1 || !versions[0]) {
    throw new Error("Expected one wasm-bindgen version in Cargo.lock");
}
const bindgenVersion = versions[0];
const installed = execFileSync("wasm-bindgen", ["--version"], { encoding: "utf8" }).trim();
if (installed !== `wasm-bindgen ${bindgenVersion}`) {
    throw new Error(`Cargo.lock requires wasm-bindgen-cli ${bindgenVersion}; found ${installed}`);
}

const targetDirectory = resolve(repositoryRoot, process.env.CARGO_TARGET_DIR ?? "target");
const artifact = join(targetDirectory, "wasm32-unknown-unknown/release/rustfs_erasure_codec_wasm.wasm");
if (!args.includes("--skip-cargo")) {
    execFileSync("cargo", [
        "build", "--locked", "--release", "--target", "wasm32-unknown-unknown",
        "-p", "rustfs-erasure-codec-wasm",
    ], { cwd: repositoryRoot, stdio: "inherit" });
}

const temporary = await mkdtemp(join(tmpdir(), "erasure-bindgen-"));
const stem = "rustfs_erasure_codec";
try {
    execFileSync("wasm-bindgen", [
        "--target", "no-modules", "--no-modules-global", "__codec_bindings",
        "--omit-default-module-path", "--out-name", stem, "--out-dir", temporary, artifact,
    ], { cwd: repositoryRoot, stdio: "inherit" });
    const generatedJs = await readFile(join(temporary, `${stem}.js`), "utf8");
    const generatedTypes = await readFile(join(temporary, `${stem}.d.ts`), "utf8");
    const generated = join(wasmRoot, "generated");
    await mkdir(generated, { recursive: true });

    // Preserve the complete generator output. The outer lexical scope gives
    // each codec its own generated module state without rewriting its ABI,
    // evaluating strings at runtime, or sharing web-target initialization.
    await writeFile(join(generated, `${stem}.js`),
        `// Generated by wasm-bindgen ${bindgenVersion}; scoped by scripts/build.mjs.\n`
        + `export function createBindings() {\n${generatedJs}\nreturn __codec_bindings;\n}\n`);
    await writeFile(join(generated, `${stem}.d.ts`), generatedTypes
        + "\nexport type GeneratedBindings = typeof __codec_bindings;\n"
        + "export declare function createBindings(): GeneratedBindings;\n");
    await copyFile(join(temporary, `${stem}_bg.wasm`), join(generated, `${stem}_bg.wasm`));

    const dist = join(wasmRoot, "dist");
    await rm(dist, { recursive: true, force: true });
    const typescriptPackage = require.resolve("typescript/package.json");
    const typescript = JSON.parse(await readFile(typescriptPackage, "utf8"));
    execFileSync(process.execPath, [
        join(dirname(typescriptPackage), typescript.bin.tsc), "--project", join(wasmRoot, "tsconfig.json"),
    ], { cwd: wasmRoot, stdio: "inherit" });
    await mkdir(join(dist, "generated"), { recursive: true });
    for (const suffix of [".js", ".d.ts", "_bg.wasm"]) {
        await copyFile(join(generated, `${stem}${suffix}`), join(dist, "generated", `${stem}${suffix}`));
    }
    await copyFile(join(repositoryRoot, "LICENSE"), join(dist, "LICENSE"));
    await writeFile(join(dist, "build-info.json"), JSON.stringify({
        wasm_bindgen: bindgenVersion,
        typescript: typescript.version,
        target: "wasm32-unknown-unknown",
        profile: "release",
    }, null, 2) + "\n");
    console.log(`Built isolated generated bindings with wasm-bindgen ${bindgenVersion}`);
} finally {
    await rm(temporary, { recursive: true, force: true });
}
